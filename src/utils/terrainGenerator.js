/**
 * ═══════════════════════════════════════════════════════════
 *  terrainGenerator.js
 *  基于组合高斯函数 + Sigmoid 的六大微地貌数学建模
 * ═══════════════════════════════════════════════════════════
 *
 *  地形形态学 (Geomorphometry) 中，绝大多数局部地貌可以通过
 *  二维高斯函数 (2D Gaussian) 的线性叠加来近似。
 *
 *  核心公式 —— 各向异性旋转高斯:
 *
 *    G(x, z) = A · exp( -[ x'²/(2σ_x²) + z'²/(2σ_z²) ] )
 *
 *  其中:
 *    x' =  (x - c_x)·cosθ + (z - c_z)·sinθ
 *    z' = -(x - c_x)·sinθ + (z - c_z)·cosθ
 *
 *  参数说明:
 *    (c_x, c_z) — 中心坐标
 *    A          — 振幅（正=隆起，负=凹陷）
 *    σ_x, σ_z   — 沿旋转后主轴的展布宽度
 *    θ          — 旋转角（控制地貌走向/延伸方向）
 *
 *  地形域: x ∈ [-5, 5], z ∈ [-5, 5]
 *  输出值: 高程（概念米），范围约 [0, 500]
 * ═══════════════════════════════════════════════════════════
 */

// ──────────────────── 常量 ────────────────────

/** 地形网格的世界尺寸 (XZ 平面) */
export const TERRAIN_SIZE = 10

/** 高程 → 场景 Y 坐标的缩放系数 (VE=1 时) */
export const HEIGHT_SCALE = 0.004

// ──────────────────── 基础数学函数 ────────────────────

/**
 * 各向异性旋转二维高斯函数 (Anisotropic Rotated 2D Gaussian)
 *
 * 地理意义:
 *   - 各向同性 (σ_x = σ_z, θ=0): 模拟山顶(Peak)或洼地(Depression)
 *   - 各向异性 (σ_x ≠ σ_z):       模拟山脊(Ridge)或山谷(Valley)
 *   - 负振幅 (A < 0):              模拟凹陷地形
 *
 * @param {number} x       - X 坐标
 * @param {number} z       - Z 坐标
 * @param {number} cx      - 中心 X
 * @param {number} cz      - 中心 Z
 * @param {number} amp     - 振幅 (米)
 * @param {number} sigmaX  - 主轴展布宽度
 * @param {number} sigmaZ  - 次轴展布宽度
 * @param {number} theta   - 旋转角 (弧度)
 * @returns {number} 该点的高程贡献 (米)
 */
function gaussian2D(x, z, cx, cz, amp, sigmaX, sigmaZ, theta = 0) {
  const dx = x - cx
  const dz = z - cz
  const cosT = Math.cos(theta)
  const sinT = Math.sin(theta)

  // 坐标旋转，对齐到高斯主轴
  const xr =  dx * cosT + dz * sinT
  const zr = -dx * sinT + dz * cosT

  const exponent = -(
    (xr * xr) / (2 * sigmaX * sigmaX) +
    (zr * zr) / (2 * sigmaZ * sigmaZ)
  )

  return amp * Math.exp(exponent)
}

/**
 * Sigmoid 函数 — 用于陡崖 (Cliff) 建模
 *
 * 地理意义:
 *   断层崖/侵蚀崖的横截面轮廓可以用 Sigmoid 函数近似：
 *   在极短的水平距离内产生极大的高差变化。
 *   参数 k (steepness) 控制崖壁的陡峭程度。
 *
 * @param {number} t         - 输入变量（与崖线的垂直距离）
 * @param {number} steepness - 陡峭系数，越大越陡
 * @returns {number} [0, 1] 区间的归一化值
 */
function sigmoid(t, steepness = 10) {
  return 1.0 / (1.0 + Math.exp(-steepness * t))
}

/**
 * 简易值噪声 — 为地形添加微观纹理
 * 避免引入外部依赖，使用多层正弦叠加模拟 Perlin 噪声效果
 *
 * @param {number} x - X 坐标
 * @param {number} z - Z 坐标
 * @returns {number} 噪声值 (大约 [-1, 1])
 */
function microNoise(x, z) {
  return (
    Math.sin(x * 2.31 + z * 1.73) * 0.35 +
    Math.sin(x * 4.07 - z * 3.51) * 0.20 +
    Math.cos(x * 1.79 + z * 5.13) * 0.15 +
    Math.sin(x * 6.83 + z * 2.67) * 0.10
  )
}

// ──────────────────── 主函数 ────────────────────

/**
 * 获取地形在 (x, z) 处的原始高程值
 *
 * ┌────────────────────────────────────────────────────┐
 * │  六大微地貌的空间布局（俯视图）                         │
 * │                                                    │
 * │  z=-5                            z=5               │
 * │   ┌─────────────────────────────────┐              │
 * │   │                                 │  x=-5        │
 * │   │   Cliff          Peak₁         │              │
 * │   │  (-3.5,-0.5)   (-1.5,-1.8)     │              │
 * │   │                  ╲ Saddle ╱     │              │
 * │   │              Depression Peak₂  │              │
 * │   │               (3.2,-1.5)(1.3,-1.5) │          │
 * │   │                                 │              │
 * │   │  Ridge                Valley    │              │
 * │   │ (-2.5, 1.8)        (1.8, 2.0)  │              │
 * │   │                                 │  x=5         │
 * │   └─────────────────────────────────┘              │
 * └────────────────────────────────────────────────────┘
 *
 * @param {number} x - X 坐标 ∈ [-5, 5]
 * @param {number} z - Z 坐标 ∈ [-5, 5]
 * @returns {number} 高程值 (概念米), 约 [0, 500]
 */
export function getHeight(x, z) {
  let h = 0

  // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  //  基底高程 + 宏观起伏
  //  模拟区域性的缓丘地形背景
  // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  h += 80 // 基底海拔 80m，确保全域为正值
  h += 15 * Math.sin(x * 0.4 + 0.5) * Math.cos(z * 0.3 + 0.3)
  h += 10 * Math.cos(x * 0.6 - 0.2) * Math.sin(z * 0.5 + 0.7)

  // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  //  ① 山顶 Peak (主峰)
  //
  //  地理学定义: 等高线呈闭合环状，中心高程最大，
  //             四周向外递减的孤立高点。
  //
  //  数学实现: 各向同性高斯 (σ_x ≈ σ_z)，正振幅
  //
  //  参数设计:
  //    中心 (-1.5, -1.8)，峰高 380m
  //    σ_x=1.4, σ_z=1.3 → 近似圆形等高线
  //    微小旋转 θ=0.1 → 打破完美对称，更自然
  // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  h += gaussian2D(x, z, -1.5, -1.8, 380, 1.4, 1.3, 0.1)

  // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  //  ② 鞍部 Saddle
  //
  //  地理学定义: 两个山顶之间的最低点，同时也是
  //             两个山谷之间的最高点。
  //             等高线呈现 "8" 字形或"蝴蝶结"状。
  //
  //  数学实现: 通过在主峰附近放置第二个山峰来
  //           **自然涌现** (emergent) 出鞍部——
  //           无需显式建模。两峰之间的高斯叠加
  //           区域天然形成马鞍形曲面。
  //
  //  副峰参数:
  //    中心 (1.3, -1.5)，峰高 320m (略低于主峰)
  //    距主峰 ≈ 2.8 个单位，σ ≈ 1.1
  //    → 鞍点大约在 (-0.1, -1.65) 处自然形成
  // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  h += gaussian2D(x, z, 1.3, -1.5, 320, 1.1, 1.2, -0.1)

  // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  //  ③ 山脊 Ridge
  //
  //  地理学定义: 从山顶向外延伸的狭长高地，
  //             等高线呈"V"形凸向低处（凸向外侧）。
  //
  //  数学实现: 各向异性高斯 (σ_z >> σ_x)
  //           σ_x=0.7 (窄) vs σ_z=3.0 (长)
  //           → 产生细长的脊线
  //           θ=π/5 → 脊线方向 NNE-SSW 走向
  // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  h += gaussian2D(x, z, -2.5, 1.8, 200, 0.7, 3.0, Math.PI / 5)

  // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  //  ④ 山谷 Valley
  //
  //  地理学定义: 两侧山脊/山坡之间的狭长凹地，
  //             等高线呈"V"形凸向高处（凸向内侧）。
  //
  //  数学实现:
  //    [a] 负振幅各向异性高斯：挖出凹槽
  //        A=-120, σ_x=0.5(窄), σ_z=2.8(长)
  //    [b] 两侧添加正高斯作为谷壁（两侧山坡）
  //        → 强化了"V"形等高线的凸出效果
  // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  h += gaussian2D(x, z, 1.8, 2.0, -120, 0.5, 2.8, -Math.PI / 4) // 凹槽
  h += gaussian2D(x, z, 2.8, 1.0,  130, 0.9, 0.9, 0)             // 右谷壁
  h += gaussian2D(x, z, 0.8, 3.2,  120, 0.8, 0.8, 0)             // 左谷壁

  // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  //  ⑤ 洼地 Depression (封闭式凹陷)
  //
  //  地理学定义: 等高线闭合，中心低于四周的封闭区域。
  //             与山顶相反，需在等高线上标注示坡线
  //             指向中心（表示向内降低）。
  //
  //  数学实现:
  //    [a] 外环: 较宽的正高斯 (σ=1.6, A=100)
  //        → 形成隆起的环形"唇缘"
  //    [b] 内核: 较窄的负高斯 (σ=0.55, A=-180)
  //        → 叠加后中心凹陷，外缘凸起
  //    净效果: 等高线闭合，内低外高
  // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  h += gaussian2D(x, z, 3.2, -1.5,  100, 1.6, 1.6, 0) // 外环（唇缘）
  h += gaussian2D(x, z, 3.2, -1.5, -180, 0.55, 0.55, 0) // 内核凹陷

  // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  //  ⑥ 陡崖 Cliff
  //
  //  地理学定义: 坡度极大的近垂直地形面。
  //             在等高线地形图上表现为多条等高线
  //             极度密集甚至重叠合并。
  //
  //  数学实现:
  //    Sigmoid 函数沿崖线法向方向产生急剧高差跃变：
  //      h_cliff = A · sigmoid(d_perp, k)
  //    其中:
  //      d_perp — 该点到崖线的法向距离
  //      k = 12 — 陡峭系数，越大崖面越陡
  //
  //    添加 cliffMask (高斯衰减) 确保崖只存在于
  //    局部区域，不影响整体地形。
  //
  //    崖线参数:
  //      中心 (-3.5, -0.5)，走向 θ=π/6 (NNE)
  //      高差 A=200m, k=12
  // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  const cxCliff = -3.5
  const czCliff = -0.5
  const dxC = x - cxCliff
  const dzC = z - czCliff
  const cliffAngle = Math.PI / 6

  // 崖线法向距离（sigmod 的输入）
  const perpDist = dxC * Math.cos(cliffAngle) + dzC * Math.sin(cliffAngle)
  // 崖线切向距离（用于 mask 衰减，控制崖的长度）
  const paraDist = -dxC * Math.sin(cliffAngle) + dzC * Math.cos(cliffAngle)
  // 高斯 mask：沿崖线方向衰减，控制崖的有限长度
  const cliffMask = Math.exp(-(paraDist * paraDist) / (2 * 1.8 * 1.8))

  h += 200 * sigmoid(perpDist, 12) * cliffMask

  // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  //  微观噪声 — 添加自然地表粗糙度
  //  模拟风化、侵蚀等作用产生的微地形起伏
  // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  h += 8 * microNoise(x, z)

  return Math.max(h, 0)
}

/**
 * 将原始高程值转换为场景 Y 坐标
 *
 * @param {number} h  - 原始高程值 (米)
 * @param {number} ve - 垂直夸大率 (Vertical Exaggeration)
 * @returns {number} 场景中的 Y 坐标
 */
export function heightToSceneY(h, ve = 1.0) {
  return h * HEIGHT_SCALE * ve
}

